async function exportXState(model: DiagramModel): Promise<FrameworkExport> {
    const parsed = await parseDiagram(serializeDiagram(model));
    const nodes = parsed.ast.elements.filter(e => e.$type === 'Transition');
    const names = new Set([...model.attributes.map(a => a.name), ...model.variables.map(v => v.name)]);
    const events = transitionEvents(model);
    const guards: string[] = [];
    const actions: string[] = [];
    const states = new Map<string, string[]>(model.states.map(s => [s.name, []]));
    const ranges = new Map(model.variables.filter(v => v.type.kind === 'range').map(v => [v.name, v.type as { low: number; high: number }]));

    model.transitions.forEach((t, i) => {
        const event = events[i];
        if (!event) return;
        const node = nodes[i];
        const parts: string[] = [];
        if (node?.$type === 'Transition' && node.guard) parts.push(js(node.guard, names));
        const updates = node?.$type === 'Transition' ? node.updates : [];
        for (const u of updates) {
            const r = ranges.get(u.variable.ref?.name ?? u.variable.$refText);
            if (r) parts.push(`inRange(${js(u.value, names)}, ${r.low}, ${r.high})`);
        }
        const entry = [`target: ${JSON.stringify(t.target)}`];
        if (parts.length > 0) {
            guards.push(`        g${i}: ({ context }) => { const v = values(${JSON.stringify(t.source)}, context); return ${parts.join(' && ')}; },`);
            entry.push(`guard: 'g${i}'`);
        }
        if (updates.length > 0) {
            const body = updates.map(u => `${u.variable.ref?.name ?? u.variable.$refText}: ${js(u.value, names)}`).join(', ');
            actions.push(`        u${i}: assign(({ context }) => { const v = values(${JSON.stringify(t.source)}, context); return { ${body} }; }),`);
            entry.push(`actions: 'u${i}'`);
        }
        states.get(t.source)!.push(`${JSON.stringify(event)}: { ${entry.join(', ')} }`);
    });

    const initial = (model.states.find(s => s.initial) ?? model.states[0]).name;
    const labels = Object.fromEntries(model.states.map(s => [s.name, Object.fromEntries(model.attributes.map(a => [a.name, s.values[a.name] === undefined ? null : jsValue(s.values[a.name], a.type.kind)]))]));
    const context = Object.fromEntries(model.variables.map(v => [v.name, jsValue(v.initial, v.type.kind)]));
    const eventUnion = [...new Set(events.filter(Boolean))].map(e => `{ type: ${JSON.stringify(e)} }`).join(' | ') || 'never';
    const contextType = model.variables.map(v => `${v.name}: ${v.type.kind === 'boolean' ? 'boolean' : v.type.kind === 'range' ? 'number' : 'string'}`).join('; ');

    const code = `/**
 * ${model.name ?? 'main'}: XState v5 machine generated by nuxmv-editor-js from the verified diagram.
 * Guards include the range checks of the updates, as in the nuXmv model.${model.states.filter(s => s.initial).length > 1 ? '\n * The diagram has several initial states; XState starts in the first one.' : ''}
 * Paste it into Stately (stately.ai/viz) to visualise it, or run it with createActor(machine).start().
 */
import { assign, setup } from 'xstate';

/** Labelling L(s): attribute values in each state (null = any value). */
export const LABELS: Record<string, Record<string, boolean | number | string | null>> = ${JSON.stringify(labels, null, 4)};

type Context = { ${contextType} };

const values = (state: string, context: Context): Record<string, unknown> => ({ ...LABELS[state], ...context, state });
const inRange = (x: number, low: number, high: number): boolean => x >= low && x <= high;

export const machine = setup({
    types: {
        context: {} as Context,
        events: {} as ${eventUnion}
    },
    guards: {
${guards.join('\n')}
    },
    actions: {
${actions.join('\n')}
    }
}).createMachine({
    id: ${JSON.stringify(model.name ?? 'main')},
    initial: ${JSON.stringify(initial)},
    context: ${JSON.stringify(context)},
    states: {
${model.states
    .map(s => {
        const on = states.get(s.name)!;
        return `        ${JSON.stringify(s.name)}: ${on.length === 0 ? "{ type: 'final' }" : `{\n            on: {\n                ${on.join(',\n                ')}\n            }\n        }`}`;
    })
    .join(',\n')}
    }
});
`;
    return { fileName: `${snakeName(model)}.machine.ts`, code, requires: [] };
}

function snakeName(model: DiagramModel): string {
    return (model.name ?? 'main').replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/[^A-Za-z0-9]+/g, '_').toLowerCase();
}

function jsValue(value: string, kind: string): boolean | number | string {
    if (kind === 'boolean') return value === 'TRUE';
    if (kind === 'range') return Number(value);
    return value;
}

/** JavaScript for a present-time expression; names are looked up in v. */
function js(e: Expression, names: Set<string>): string {
    if (isBooleanLiteral(e)) return e.value === 'TRUE' ? 'true' : 'false';
    if (isNumberLiteral(e)) return String(e.value);
    if (isStateVariable(e)) return 'v.state';
    if (isNameReference(e)) return names.has(e.name) ? `(v[${JSON.stringify(e.name)}] as any)` : JSON.stringify(e.name);
    if (isUnaryExpression(e)) {
        if (e.operator === '!') return `!(${js(e.operand, names)})`;
        if (e.operator === '-') return `-(${js(e.operand, names)})`;
        throw new Error(`Temporal operator ${e.operator} in a guard or update.`);
    }
    if (isBinaryExpression(e)) {
        const a = js(e.left, names);
        const b = js(e.right, names);
        switch (e.operator) {
            case '&':
                return `(${a} && ${b})`;
            case '|':
                return `(${a} || ${b})`;
            case '->':
                return `(!(${a}) || ${b})`;
            case '<->':
            case 'xnor':
                return `(${a} === ${b})`;
            case 'xor':
                return `(${a} !== ${b})`;
            case '=':
                return `(${a} === ${b})`;
            case '!=':
                return `(${a} !== ${b})`;
            case '/':
                return `Math.trunc(${a} / ${b})`;
            case 'mod':
                return `(${a} % ${b})`;
            case 'U':
            case 'V':
            case 'S':
            case 'T':
                throw new Error(`Temporal operator ${e.operator} in a guard or update.`);
            default:
                return `(${a} ${e.operator} ${b})`;
        }
    }
    throw new Error('Unsupported expression in a guard or update.');
}
